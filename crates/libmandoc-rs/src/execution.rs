/// Half-open byte range in the report's immutable byte pool.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct PoolRange {
    /// First byte.
    pub start: u32,
    /// Number of bytes.
    pub length: u32,
}

impl PoolRange {
    pub(crate) fn as_range(self) -> Option<Range<usize>> {
        let start = usize::try_from(self.start).ok()?;
        let end = start.checked_add(usize::try_from(self.length).ok()?)?;
        Some(start..end)
    }
}

