/// Fully owned result of one parse and one native terminal traversal.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct NativeExecutionReport {
    pub(crate) pool: Vec<u8>,
    /// Native work units charged by this execution.
    pub work_units: u64,
    /// Total records stored across all typed tables.
    pub record_count: u64,
    /// Peak native terminal buffer capacity charged to this execution.
    pub buffer_cells: u64,
    /// Participating sources.
    pub sources: Vec<ExecutionSource>,
    /// Final-tree node registry.
    pub nodes: Vec<ExecutionNode>,
    /// Native buffer lifetimes referenced by atoms, fragments, and flushes.
    pub buffer_generations: Vec<ExecutionBufferGeneration>,
    /// Buffer atoms.
    pub atoms: Vec<ExecutionAtom>,
    /// Device fragments.
    pub fragments: Vec<ExecutionFragment>,
    /// Native field segments.
    pub flushes: Vec<ExecutionFlush>,
    /// Ordered boundary requests and effects.
    pub boundaries: Vec<ExecutionBoundary>,
    /// Objective native geometry.
    pub geometry: Vec<ExecutionGeometry>,
    /// Execution scopes and instantaneous state transitions.
    pub wrappers: Vec<ExecutionWrapper>,
    /// Semantic references observed at their native macro handlers.
    pub references: Vec<ExecutionReference>,
    /// Native target attachments.
    pub anchors: Vec<ExecutionAnchor>,
    /// Non-fatal report diagnostics.
    pub diagnostics: Vec<ExecutionDiagnostic>,
}

impl NativeExecutionReport {
    /// Number of bytes in the immutable report pool.
    #[must_use]
    pub fn pool_len(&self) -> usize {
        self.pool.len()
    }

    /// Whether the immutable report pool is empty.
    #[must_use]
    pub fn pool_is_empty(&self) -> bool {
        self.pool.is_empty()
    }

    /// Borrow bytes from the immutable report pool.
    #[must_use]
    pub fn pool_bytes(&self, range: PoolRange) -> Option<&[u8]> {
        self.pool.get(range.as_range()?)
    }
}

/// Limits independently bounding native execution work and storage.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct ExecutionLimits {
    /// Maximum final-tree nodes.
    pub max_nodes: u64,
    /// Maximum syntax-tree depth.
    pub max_depth: u64,
    /// Maximum charged native work units.
    pub max_work: u64,
    /// Maximum records across all typed tables.
    pub max_records: u64,
    /// Maximum pooled source and operand bytes.
    pub max_pool_bytes: u64,
    /// Maximum tracked native buffer cells.
    pub max_buffer_cells: u64,
}

impl Default for ExecutionLimits {
    fn default() -> Self {
        Self {
            max_nodes: 1_000_000,
            max_depth: 256,
            max_work: 16_000_000,
            max_records: 4_000_000,
            max_pool_bytes: 16 * 1024 * 1024,
            max_buffer_cells: 1_000_000,
        }
    }
}

/// A document and the facts produced by its single native execution.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ExecutionReport {
    /// Fully owned parsed syntax tree.
    pub document: crate::Document,
    /// Non-fatal parser diagnostics.
    pub diagnostics: Vec<crate::Diagnostic>,
    /// Fully owned native execution facts.
    pub execution: NativeExecutionReport,
}

/// Stable failure category for the combined parse/execute boundary.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ExecutionErrorKind {
    /// Input policy cannot be represented by this execution version.
    Unsupported,
    /// A configured execution budget was exhausted.
    Budget,
    /// Native storage could not be allocated.
    Allocation,
    /// Parsing or native execution failed.
    Native,
    /// The C/Rust transfer contract was rejected.
    Transfer,
}

/// Failure from the combined parse/execute boundary.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ExecutionError {
    /// Logical source path.
    pub path: PathBuf,
    /// Stable category.
    pub kind: ExecutionErrorKind,
    /// Human-readable detail.
    pub message: String,
}

impl fmt::Display for ExecutionError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(formatter, "{}: {}", self.path.display(), self.message)
    }
}

impl std::error::Error for ExecutionError {}
