/// Stable flags retained for one native table cell.
#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
pub struct ExecutionTableCellFlags(pub u32);

impl ExecutionTableCellFlags {
    /// The layout requested top alignment.
    pub const TOP_ALIGNED: u32 = 1 << 0;
    /// The layout requested upward vertical adjustment.
    pub const UP: u32 = 1 << 1;
    /// The layout requested bottom alignment.
    pub const BOTTOM_ALIGNED: u32 = 1 << 2;
    /// The cell width is ignored while calculating column width.
    pub const WIDTH_IGNORED: u32 = 1 << 3;
    /// The column participates in equal-width calculation.
    pub const EQUAL_WIDTH: u32 = 1 << 4;
    /// The column may consume the maximum available width.
    pub const MAX_WIDTH: u32 = 1 << 5;
    /// The source used a multiline `T{` / `T}` text block.
    pub const TEXT_BLOCK: u32 = 1 << 6;
    /// Native parsing established that source-backed enrichment is safe.
    pub const SOURCE_RECOVERY_SAFE: u32 = 1 << 7;
    /// This cell continues content owned by a preceding row.
    pub const VERTICAL_CONTINUATION: u32 = 1 << 8;

    /// Return whether a stable flag is present.
    #[must_use]
    pub const fn contains(self, flag: u32) -> bool {
        self.0 & flag != 0
    }
}

