//! Owned facts captured from one authoritative native terminal execution.

use std::{fmt, ops::Range, path::PathBuf};

/// Sentinel-free report-local identity of a syntax node.
#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
pub struct ExecutionNodeKey(pub u32);

/// Report-local identity of a buffered atom.
#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
pub struct AtomKey(pub u32);

/// Report-local identity of an emitted fragment.
#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
pub struct FragmentKey(pub u32);

/// Half-open byte range in the report's immutable byte pool.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct PoolRange {
    /// First byte.
    pub start: u32,
    /// Number of bytes.
    pub length: u32,
}

impl PoolRange {
    pub(crate) fn as_range(self) -> Option<Range<usize>> {
        let start = usize::try_from(self.start).ok()?;
        let end = start.checked_add(usize::try_from(self.length).ok()?)?;
        Some(start..end)
    }
}

/// Kind of one native terminal-buffer atom.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum AtomKind {
    /// Printable glyph.
    Glyph,
    /// Breakable space.
    BreakableSpace,
    /// Non-breaking space.
    NonBreakingSpace,
    /// Discretionary hyphen.
    BreakableHyphen,
    /// Non-printing zero-width marker.
    ZeroWidth,
    /// Literal tab.
    Tab,
    /// Tab-origin reference marker.
    TabReference,
    /// Backspace used by terminal overstrike.
    Backspace,
    /// Word-end line-break request produced by `\p`.
    WordEndBreak,
    /// Zero-width discretionary break point produced by `\:`.
    BreakPoint,
}

/// Why an atom entered the native buffer.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum AtomRole {
    /// Derived from a formatter word operand.
    Authored,
    /// Implicit inter-word spacing.
    ImplicitSpace,
    /// Device overstrike used to express a font.
    FontDecoration,
    /// Text generated by a manual macro handler.
    MacroGenerated,
    /// Text generated by the output device.
    DeviceGenerated,
}

/// Final fate of one atom in the captured execution.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum AtomDisposition {
    /// Still buffered when the report was sealed.
    Buffered,
    /// Emitted by the device.
    Emitted,
    /// Consumed as layout input without visible output.
    Consumed,
    /// Replaced by a later buffer mutation.
    Replaced,
    /// Discarded as trailing layout whitespace.
    TrailingDiscard,
}

/// Effective terminal font at an execution point.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ExecutionFont {
    /// Roman/default.
    Roman,
    /// Bold.
    Bold,
    /// Underline/italic terminal projection.
    Underline,
    /// Bold underline.
    BoldUnderline,
}

/// Why one fragment was emitted by the native device.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum FragmentRole {
    /// Document content.
    Content,
    /// Device decoration used to project a font.
    FontDecoration,
    /// A margin character generated by `.mc`.
    MarginDecoration,
    /// A page header or footer generated by the terminal device.
    PageDecoration,
}

/// Native newline or vertical-space request.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum BoundaryRequest {
    /// Conditional newline.
    Newline,
    /// Unconditional vertical space.
    VerticalSpace,
    /// Native `endline()` operation, including margin output.
    Endline,
    /// Device line completion.
    DeviceEndline,
}

/// Observed result of a boundary request.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum BoundaryEffect {
    /// State changed without output.
    NoOutput,
    /// Buffered content was flushed.
    Flushed,
    /// A device line ended.
    EndedLine,
    /// A blank device line was added.
    AddedVerticalSpace,
}

/// Kind of a native geometry observation.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum GeometryKind {
    /// Horizontal advance.
    Advance,
    /// Glyph placement.
    Glyph,
    /// Device line completion.
    Endline,
    /// Field geometry.
    Field,
}

/// Unit carried by a geometry observation.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum GeometryUnit {
    /// Native terminal basic units.
    Basic,
    /// Native buffer slot.
    BufferSlot,
    /// Device line number.
    DeviceLine,
}

/// Type of report record causing one geometry observation.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum GeometryOriginKind {
    /// No record-level origin is available.
    None,
    /// A terminal-buffer atom.
    Atom,
    /// A native flush segment.
    Flush,
    /// A boundary request.
    Boundary,
    /// An emitted fragment.
    Fragment,
}

/// Stable kind of an execution scope or instantaneous state transition.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ExecutionWrapperKind {
    /// Syntax-node execution interval.
    Node,
    /// Instantaneous font-stack transition.
    Font,
}

/// Semantic destination kind observed at the native macro handler.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ExecutionReferenceKind {
    /// External URI.
    ExternalUri,
    /// Email address.
    Email,
    /// Manual name and optional section.
    Manual,
    /// Same-document section phrase.
    SameDocumentSection,
}

/// Relationship between an execution fact and surrounding emitted content.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ExecutionAffinity {
    /// The fact spans inline formatter atoms.
    Inline,
    /// The fact attaches before the next output owned by its node.
    BeforeOutput,
}

/// One input source participating in the execution.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ExecutionSource {
    /// Report-local source key.
    pub key: u32,
    /// Including source, absent for the root.
    pub parent: Option<u32>,
    /// Node issuing the include, absent for the root.
    pub include_node: Option<ExecutionNodeKey>,
    /// Logical source path.
    pub path: PathBuf,
}

/// Stable structural identity and source location for one syntax node.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ExecutionNode {
    /// Dense report-local node key.
    pub key: ExecutionNodeKey,
    /// Parent node.
    pub parent: Option<ExecutionNodeKey>,
    /// Source key.
    pub source: u32,
    /// One-based source line, or zero when unavailable.
    pub line: u32,
    /// One-based source column, or zero when unavailable.
    pub column: u32,
    /// Stable node-kind code shared with the owned AST snapshot.
    pub kind: u32,
    /// Stable node flags.
    pub flags: u32,
    /// Source macro name, when applicable.
    pub macro_name: Option<String>,
}

/// One lifetime of a native terminal column buffer.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ExecutionBufferGeneration {
    /// Dense report-local generation key.
    pub key: u32,
    /// Native terminal column buffer identity.
    pub buffer: u32,
    /// Monotonic generation within that buffer.
    pub generation: u32,
    /// Allocated native cells available to this generation.
    pub capacity: u32,
    /// Highest logical half-open buffer position observed.
    pub extent: u32,
    /// Why this generation ended.
    pub close_reason: BufferCloseReason,
    /// Execution interval containing every fact referring to this generation.
    pub open_sequence: u64,
    /// Execution point at which the generation was reset or the report sealed.
    pub close_sequence: u64,
}

/// Why a native buffer generation ended.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum BufferCloseReason {
    /// `term_flushln()` reset the buffer after consuming the field.
    Reset,
    /// The report was sealed while the reusable buffer remained allocated.
    ReportEnd,
}

/// One native terminal-buffer atom and its provenance.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ExecutionAtom {
    /// Atom identity.
    pub key: AtomKey,
    /// Native terminal column-buffer identity.
    pub buffer: Option<u32>,
    /// Buffer generation.
    pub generation: Option<u32>,
    /// Owning buffer-generation fact, absent for direct device output.
    pub buffer_generation: Option<u32>,
    /// Buffer slot, absent for direct device output.
    pub slot: Option<u32>,
    /// Atom kind.
    pub kind: AtomKind,
    /// Atom origin role.
    pub role: AtomRole,
    /// Scalar before device normalization.
    pub input_scalar: u32,
    /// Scalar emitted to the device.
    pub display_scalar: u32,
    /// Width in native basic units.
    pub width_bu: i64,
    /// Owning syntax node.
    pub node: Option<ExecutionNodeKey>,
    /// Source key.
    pub source: u32,
    /// Formatter word bytes associated with this atom.
    pub operand: Option<PoolRange>,
    /// Effective font.
    pub font: ExecutionFont,
    /// Innermost wrapper key.
    pub wrapper: Option<u32>,
    /// Replacing atom, when overwritten.
    pub replaced_by: Option<AtomKey>,
    /// Final atom disposition.
    pub disposition: AtomDisposition,
    /// Total execution order.
    pub sequence: u64,
}

