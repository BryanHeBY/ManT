/// One accepted field segment from `term_fill`/`term_field`.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ExecutionFlush {
    /// Flush-segment identity.
    pub key: u32,
    /// Owning node.
    pub node: Option<ExecutionNodeKey>,
    /// Native buffer and generation.
    pub buffer: u32,
    /// Native buffer generation.
    pub generation: u32,
    /// Owning buffer-generation fact.
    pub buffer_generation: u32,
    /// Buffer range scanned by the native fill algorithm.
    pub scanned: Range<u32>,
    /// Buffer range accepted for this field segment.
    pub accepted: Range<u32>,
    /// Buffer range consumed by the device.
    pub consumed: Range<u32>,
    /// Buffer range remaining for subsequent segments.
    pub remaining: Range<u32>,
    /// Emitted fragment range.
    pub fragments: Range<u32>,
    /// Stable terminal flags before the flush.
    pub flags_before: u32,
    /// Stable terminal flags after the flush.
    pub flags_after: u32,
    /// Boundary causally containing this flush.
    pub boundary: Option<u32>,
    /// Actual fixed-CVS branch taken after this fill decision.
    pub outcome: FlushOutcome,
    /// Leading space in basic units.
    pub leading_bu: i64,
    /// Accepted content width in basic units.
    pub content_bu: i64,
    /// Field width in basic units.
    pub field_bu: i64,
    /// Target width in basic units.
    pub target_bu: i64,
    /// Tab offset before the segment.
    pub taboff_before: i64,
    /// Tab offset after the segment.
    pub taboff_after: i64,
    /// Visual position before/after the segment.
    pub visual_before: i64,
    /// Visual position after the segment.
    pub visual_after: i64,
    /// Total execution order.
    pub sequence: u64,
    /// Execution point at which the branch outcome became known.
    pub outcome_sequence: u64,
}

/// Actual branch taken by one native `term_flushln()` fill segment.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum FlushOutcome {
    /// `term_fill()` accepted no visible field content.
    NoContent,
    /// The accepted field exhausted all non-layout content.
    Exhausted,
    /// Single-column output ended a device line and continued this buffer.
    Wrapped,
    /// Multi-column output yielded the remaining buffer to another column.
    DeferredColumn,
}

