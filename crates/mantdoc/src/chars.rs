pub(crate) fn lookup(name: &str) -> Option<SpecialCharacter> {
    let codepoint = CATALOG
        .binary_search_by_key(&name, |(candidate, _)| *candidate)
        .ok()
        .map(|index| CATALOG[index].1)?;
    match codepoint {
        0 => Some(SpecialCharacter::ZeroWidth),
        value => char::from_u32(value).map(SpecialCharacter::Visible),
    }
}

#[cfg(test)]
mod tests {
    use super::{CATALOG, SpecialCharacter, special_character};

    #[test]
    fn exposes_the_complete_pinned_mandoc_catalog() {
        assert_eq!(CATALOG.len(), 346);
        assert!(CATALOG.windows(2).all(|pair| pair[0].0 <= pair[1].0));
        assert!(
            CATALOG
                .iter()
                .all(|(_, value)| *value == 0 || char::from_u32(*value).is_some())
        );
        for (name, expected) in [
            ("at", '@'),
            ("ga", '`'),
            ("oq", '‘'),
            ("->", '→'),
            ("<-", '←'),
            ("mu", '×'),
            ("lB", '['),
            ("rB", ']'),
            ("a\"", '˝'),
            ("'", '´'),
        ] {
            assert_eq!(
                special_character(name),
                Some(SpecialCharacter::Visible(expected)),
                "name={name}"
            );
        }
        assert_eq!(special_character(":"), Some(SpecialCharacter::ZeroWidth));
        assert_eq!(special_character("not-a-mandoc-character"), None);
    }
}
