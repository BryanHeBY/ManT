#[cfg(test)]
#[test]
fn words_are_sorted_unique_and_complete_tokens() {
    assert!(WORDS.windows(2).all(|pair| pair[0] < pair[1]));
    for word in WORDS {
        assert!(contains(word));
    }
    assert!(!contains("return-value"));
    assert!(!contains("structural"));
}
