pub(super) fn latex_fence(value: &str) -> Option<&'static str> {
    Some(match value {
        "" => ".",
        "(" => "(",
        ")" => ")",
        "[" => "[",
        "]" => "]",
        "{" => "\\{",
        "}" => "\\}",
        "|" => "|",
        "‖" => "\\Vert",
        "⟨" => "\\langle",
        "⟩" => "\\rangle",
        "⌈" => "\\lceil",
        "⌉" => "\\rceil",
        "⌊" => "\\lfloor",
        "⌋" => "\\rfloor",
        "/" => "/",
        "\\" => "\\backslash",
        _ => return None,
    })
}

pub(super) fn latex_accent(kind: EquationDecorationKind) -> Option<&'static str> {
    Some(match kind {
        EquationDecorationKind::Dot => "\\dot{",
        EquationDecorationKind::DoubleDot => "\\ddot{",
        EquationDecorationKind::Hat => "\\widehat{",
        EquationDecorationKind::Tilde => "\\widetilde{",
        EquationDecorationKind::Overbar => "\\overline{",
        EquationDecorationKind::Underline => "\\underline{",
        EquationDecorationKind::Vector => "\\overrightarrow{",
        EquationDecorationKind::BidirectionalVector => "\\overleftrightarrow{",
        EquationDecorationKind::Custom => return None,
    })
}
