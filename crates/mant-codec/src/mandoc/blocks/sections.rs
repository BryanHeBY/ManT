//! Section/root ownership and source-ordered heading reconstruction.
use super::{
    Block, FormatterRowBoundary, LoweringContext, Node, NodeKind, ScopeFlow, Section,
    first_part_children, is_native_transparent_sibling, lower_scope, source_span,
    update_paragraph_distance,
};
use crate::mandoc::{
    formatter::FormatterState, inline::authored_section_phrase,
    layout::execute_vertical_spacing_after_newline, source_context::MdocSectionContext,
};
use libmandoc_rs::{
    MacroToken::{Man, Mdoc},
    ManMacro, MdocMacro,
};

pub(in crate::mandoc) fn lower_document_structure(
    root: &Node,
    context: &mut LoweringContext<'_>,
) -> (Vec<Block>, Vec<Section>) {
    let mut paragraph_distance = 1;
    let mut formatter = crate::mandoc::formatter::FormatterState::default();
    formatter.execution.escape_coverage = context.escape_coverage.clone();
    formatter.execution.zero_advance.annotations = Some(context.annotations.clone());
    let mut root_blocks = Vec::new();
    let mut sections = Vec::new();
    let mut root_start = 0;
    let mut previous_native = None;
    for (index, node) in root.children.iter().enumerate() {
        let predecessor = previous_native;
        if !is_native_transparent_sibling(node) {
            previous_native = Some(node);
        }
        // Accept both `.SH` and a `.SS` that appears directly at the document
        // root. Well-formed pages nest `.SS` inside a `.SH` body, but pages
        // generated by tools such as Pandoc emit only `.SS` blocks with no
        // enclosing `.SH`. Without this, such pages lower to zero sections and
        // the whole document is reported as unreadable.
        if !is_section(node, true) && !is_section(node, false) {
            continue;
        }
        let entry = SectionEntry::for_node(node, predecessor);
        let flow = ScopeFlow::settled(
            crate::mandoc::layout::SourceIndent::default(),
            formatter.spacing_enabled(),
        );
        // A preceding section already ran its BODY post. A nonempty root
        // slice can still own a row that this BLOCK pre must finish.
        let mut heading = None;
        if root_start < index {
            let (blocks, prepared) = lower_before_heading(
                &root.children[root_start..index],
                context,
                &mut paragraph_distance,
                &mut formatter,
                flow,
                node,
                entry,
            );
            root_blocks.extend(blocks);
            heading = prepared;
        } else {
            root_blocks.extend(lower_scope(
                &[],
                context,
                &mut paragraph_distance,
                &mut formatter,
                flow,
            ));
        }
        root_start = index + 1;
        let spacing_before_lines = entry.finish(paragraph_distance, &mut formatter);
        sections.push(lower_section(
            node,
            context,
            spacing_before_lines,
            &mut paragraph_distance,
            &mut formatter,
            true,
            heading,
        ));
    }
    let spacing_enabled = formatter.spacing_enabled();
    root_blocks.extend(lower_scope(
        &root.children[root_start..],
        context,
        &mut paragraph_distance,
        &mut formatter,
        ScopeFlow::settled(
            crate::mandoc::layout::SourceIndent::default(),
            spacing_enabled,
        ),
    ));
    report_presentation_reductions(context, &formatter);
    (root_blocks, sections)
}

fn report_presentation_reductions(
    context: &LoweringContext<'_>,
    formatter: &crate::mandoc::formatter::FormatterState,
) {
    if formatter.execution.partial_row_alignment {
        context.diagnostics.borrow_mut().push(mant_ir::Diagnostic {
            impact: mant_ir::DiagnosticImpact::None,
            level: mant_ir::DiagnosticLevel::Warning,
            code: Some("manual.partial-row-alignment".into()),
            message: "alignment of a later field on an already printed row was simplified to left-to-right reading; accepted text, word boundaries and hard rows were retained".into(),
            source: None,
        });
    }
}

type PreparedHeading = (Vec<mant_ir::Inline>, u16);

fn lower_before_heading(
    nodes: &[Node],
    context: &LoweringContext<'_>,
    paragraph_distance: &mut u16,
    formatter: &mut FormatterState,
    flow: ScopeFlow<'_>,
    next: &Node,
    entry: SectionEntry,
) -> (Vec<Block>, Option<PreparedHeading>) {
    let mut lowerer = super::walk_scope(nodes, context, paragraph_distance, formatter, flow);
    // With .PD 0, man_term.c::pre_SH/pre_SS can leave the input column
    // intact. Do not publish a word that HEAD's real flush can still reject.
    let prepared = if context.macro_set == libmandoc_rs::MacroSet::Man
        && !entry.needs_newline(*lowerer.paragraph_distance)
    {
        lowerer
            .state
            .with_pending_section_output(|formatter, previous| {
                prepare_heading(
                    next,
                    context,
                    formatter,
                    MdocSectionContext::Other,
                    previous,
                )
            })
    } else {
        None
    };
    let boundary = if prepared.is_some() {
        FormatterRowBoundary::SectionHeadConsumed
    } else {
        FormatterRowBoundary::BeforeSection(entry)
    };
    (lowerer.finish_into(formatter, boundary), prepared)
}

fn prepare_heading(
    node: &Node,
    context: &LoweringContext<'_>,
    formatter: &mut FormatterState,
    section_context: MdocSectionContext,
    previous: &mut Vec<mant_ir::Inline>,
) -> PreparedHeading {
    let head = first_part_children(node, NodeKind::Head);
    // SH/Sh and SS/Ss assign their heading origin in pre, and BODY's
    // ordinary manual origin afterwards (man_term.c::pre_SH/pre_SS,
    // mdoc_term.c::termp_sh_pre/termp_ss_pre). No prior ti offset leaks.
    formatter.row_presentation.offset_shift = 0;
    formatter.row_presentation.parent = 0;
    context.lower_section_heading(
        node,
        crate::mandoc::source_context::HeadNodes {
            // blk_full() emits leading delimiter TEXT before allocating
            // Sh/Ss HEAD. It executes before the HEAD's bold pre, remains
            // in this heading owner, and is not part of its deroff identity.
            before: node
                .children
                .iter()
                .position(|child| child.kind == NodeKind::Head)
                .map_or(&[], |head| &node.children[..head]),
            content: head,
            source_origin_units: None,
        },
        formatter,
        section_context == MdocSectionContext::Authors,
        previous,
    )
}

fn lower_section(
    node: &Node,
    context: &mut LoweringContext<'_>,
    spacing_before_lines: u16,
    paragraph_distance: &mut u16,
    formatter: &mut FormatterState,
    top_level: bool,
    prepared: Option<PreparedHeading>,
) -> Section {
    let section_context = if top_level {
        native_mdoc_section_context(node)
    } else {
        context.active_mdoc_section()
    };
    let authored_title = authored_section_phrase(
        first_part_children(node, NodeKind::Head),
        context.default_name,
    );
    let (mut heading, blank_heading_rows) = prepared.unwrap_or_else(|| {
        prepare_heading(node, context, formatter, section_context, &mut Vec::new())
    });
    // Allocate IDs in visible document order. Besides being deterministic for
    // consumers, this makes `.Sx` resolution independent of tree recursion.
    let (id, fragment_aliases) = context.section_identity_for(&authored_title, node);
    let body = first_part_children(node, NodeKind::Body);
    formatter.row_presentation.offset_shift = 0;
    formatter.row_presentation.parent = 5 * 24;
    // mdoc Sh/Ss BODY resets tabs after HEAD; man SH/SS does not
    // (mdoc_term.c::termp_sh_pre/termp_ss_pre, man_term.c::pre_SH/pre_SS).
    if context.macro_set == libmandoc_rs::MacroSet::Mdoc {
        formatter.reset_default_tabs();
    }
    let first_subsection = body
        .iter()
        .position(|child| is_section(child, false))
        .unwrap_or(body.len());
    let previous_section = context.replace_mdoc_section(section_context);
    if top_level && section_context == crate::mandoc::source_context::MdocSectionContext::Authors {
        formatter.enter_authors_section();
    }
    let spacing_enabled = formatter.spacing_enabled();
    let mut flow = ScopeFlow::settled(
        crate::mandoc::layout::SourceIndent::default(),
        spacing_enabled,
    );
    let (blocks, child_heading) = if let Some(subsection) = body.get(first_subsection) {
        let nodes = &body[..first_subsection];
        let previous = nodes
            .iter()
            .rfind(|node| !is_native_transparent_sibling(node));
        lower_before_heading(
            nodes,
            context,
            paragraph_distance,
            formatter,
            flow,
            subsection,
            SectionEntry::for_node(subsection, previous),
        )
    } else {
        flow.row_boundary = FormatterRowBoundary::SectionBodyPost;
        (
            lower_scope(body, context, paragraph_distance, formatter, flow),
            None,
        )
    };
    let children = lower_subsections(
        body,
        first_subsection,
        context,
        paragraph_distance,
        formatter,
        child_heading,
    );
    context.replace_mdoc_section(previous_section);
    Section {
        id: id.into(),
        fragment_aliases,
        heading: mant_ir::Heading {
            inline_layout: crate::mandoc::inline::take_inline_layout(&mut heading),
            content: heading,
            source: node
                .children
                .iter()
                .find(|child| child.kind == NodeKind::Head)
                .and_then(source_span),
        },
        spacing_before_lines: spacing_before_lines.saturating_add(blank_heading_rows),
        blocks,
        children,
        source: source_span(node),
    }
}

fn lower_subsections(
    body: &[Node],
    first_subsection: usize,
    context: &mut LoweringContext<'_>,
    paragraph_distance: &mut u16,
    formatter: &mut crate::mandoc::formatter::FormatterState,
    mut heading: Option<PreparedHeading>,
) -> Vec<Section> {
    let (body, subsections) = body.split_at(first_subsection);
    let mut previous_native = body
        .iter()
        .rev()
        .find(|node| !is_native_transparent_sibling(node));
    let mut children = Vec::new();
    for child in subsections {
        let predecessor = previous_native;
        if !is_native_transparent_sibling(child) {
            previous_native = Some(child);
        }
        update_paragraph_distance(child, paragraph_distance);
        if !is_section(child, false) {
            continue;
        }
        let child_spacing =
            SectionEntry::for_node(child, predecessor).finish(*paragraph_distance, formatter);
        let child = lower_section(
            child,
            context,
            child_spacing,
            paragraph_distance,
            formatter,
            false,
            heading.take(),
        );
        children.push(child);
    }
    children
}

/// Native section BLOCK pre, independent of the preceding IR owner.
#[derive(Clone, Copy, Eq, PartialEq)]
pub(in crate::mandoc) enum SectionEntry {
    None,
    Newline,
    ParagraphDistance,
    OneVerticalRow,
}

impl SectionEntry {
    fn for_node(node: &Node, previous: Option<&Node>) -> Self {
        match node.macro_token.as_ref() {
            Some(Man(ManMacro::Sh | ManMacro::Ss)) => {
                // man_term.c::pre_SH/pre_SS use roff_node_child(): a BODY
                // containing only transparent requests is empty here.
                let requests_gap = previous.is_some_and(|previous| {
                    previous.macro_token != node.macro_token
                        || first_part_children(previous, NodeKind::Body)
                            .iter()
                            .any(|child| !is_native_transparent_sibling(child))
                });
                if requests_gap {
                    Self::ParagraphDistance
                } else {
                    Self::None
                }
            }
            Some(Mdoc(MdocMacro::Sh)) => {
                // mdoc_term.c::termp_sh_pre reads the raw BODY child, not
                // roff_node_child(). Even a transparent child counts.
                let follows_empty_sh = previous.is_some_and(|previous| {
                    previous.macro_token == node.macro_token
                        && first_part_children(previous, NodeKind::Body).is_empty()
                });
                if follows_empty_sh {
                    Self::None
                } else {
                    Self::OneVerticalRow
                }
            }
            Some(Mdoc(MdocMacro::Ss)) => {
                // termp_ss_pre uses only roff_node_prev(); empty Ss counts.
                if previous.is_some() {
                    Self::OneVerticalRow
                } else {
                    Self::Newline
                }
            }
            _ => Self::None,
        }
    }

    const fn requested_rows(self, paragraph_distance: u16) -> u16 {
        match self {
            Self::None | Self::Newline => 0,
            Self::ParagraphDistance => paragraph_distance,
            Self::OneVerticalRow => 1,
        }
    }

    pub(super) const fn needs_newline(self, paragraph_distance: u16) -> bool {
        matches!(self, Self::Newline) || self.requested_rows(paragraph_distance) > 0
    }

    fn finish(self, paragraph_distance: u16, formatter: &mut FormatterState) -> u16 {
        let requested = self.requested_rows(paragraph_distance);
        if self.needs_newline(paragraph_distance) {
            // The conditional flush ran in the old owner or at its BODY
            // post. term_newln also selects NOSPACE even on an empty row.
            formatter.execution.select_native_no_space();
        }
        execute_vertical_spacing_after_newline(formatter, requested)
    }
}

/// Consume the parser's normalized `sec` rather than reconstructing it from
/// the authored heading. CVS `mdoc_state.c::state_sh()` already decided when
/// a direct text head names a standard section.
fn native_mdoc_section_context(node: &Node) -> crate::mandoc::source_context::MdocSectionContext {
    match node.section {
        libmandoc_rs::NormalizedSection::Synopsis => {
            crate::mandoc::source_context::MdocSectionContext::Synopsis
        }
        libmandoc_rs::NormalizedSection::Authors => {
            crate::mandoc::source_context::MdocSectionContext::Authors
        }
        _ => crate::mandoc::source_context::MdocSectionContext::Other,
    }
}

pub(super) fn is_section(node: &Node, top_level: bool) -> bool {
    matches!(
        (node.macro_token.as_ref(), top_level),
        (Some(Mdoc(MdocMacro::Sh) | Man(ManMacro::Sh)), true)
            | (Some(Mdoc(MdocMacro::Ss) | Man(ManMacro::Ss)), false)
    )
}
